// Embeds the sample pictures (samples/*.pbm, the same ones that come with the Flipper app) into
// js/ui/samples.js, so the transmitter offers them even when the page is opened from disk (a
// file:// page can't read files next to it). Run: node tools/make_web_samples.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const DIR = new URL('../samples/', import.meta.url);
const ORDER = ['Sphere', 'Torus', 'Cube', 'Cone', 'Floor', 'Test pattern'];
const names = readdirSync(DIR).filter((f) => f.endsWith('.pbm')).map((f) => f.slice(0, -4))
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99));
const out = names.map((name) => {
  const buf = readFileSync(new URL(`${name}.pbm`, DIR));
  // P4 header: "P4", width, height, then one whitespace byte before the bits
  const m = buf.toString('latin1', 0, 64).match(/^P4\s+(?:#[^\n]*\n\s*)*(\d+)\s+(\d+)\s/);
  if (!m || +m[1] !== 400 || +m[2] !== 240) throw new Error(`${name}: not a 400x240 P4 PBM`);
  const bits = buf.subarray(m[0].length, m[0].length + 400 * 240 / 8);
  return { name, bits: bits.toString('base64') };
});
writeFileSync(new URL('../js/ui/samples.js', import.meta.url),
  `// Generated by tools/make_web_samples.mjs from samples/*.pbm. Do not edit by hand.\n` +
  `export const SAMPLES = ${JSON.stringify(out)};\n`);
console.log(names.join(', '));
